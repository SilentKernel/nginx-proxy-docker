#!/usr/bin/env bash
# Regenerates go/docker-gen/{go.mod,go.sum} and go/forego/{go.mod,go.sum}: upstream's module files
# at DOCKER_GEN_COMMIT / FOREGO_COMMIT, with the modules of DOCKER_GEN_GO_GET / FOREGO_GO_GET
# raised (`go get`, then `go mod tidy`), in our go-docker image (versions.env). The Dockerfile
# builds with these files only (-mod=readonly) and refuses them when their first line does not
# name the commit it builds: rerun this after changing a commit or a bump list, review the diff,
# commit. Never edit the files by hand.
#   scripts/update-go-deps.sh            both tools
#   scripts/update-go-deps.sh forego     one
# Needs Docker, the registry login (go-docker), github.com and proxy.golang.org.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
set -a
# shellcheck source=../versions.env
. "$ROOT/versions.env"
set +a

gen() {   # <tool> <commit> <go get arguments>
    local tool="$1" commit="$2" bumps="$3" tmp
    tmp="$(mktemp -d)"
    echo "==> ${tool} ${commit:0:12}: go get ${bumps}"
    # the files come back as a tar on stdout: no bind mount needed (works on Docker Desktop and CI)
    docker run --rm --platform "$PLATFORM" --entrypoint sh \
        -e TOOL="$tool" -e COMMIT="$commit" -e BUMPS="$bumps" "${GO_BASE_IMAGE}:${GO_BASE_TAG}" -ec '
            exec 3>&1 1>&2
            mkdir -p /src && cd /src
            git init -q . && git fetch -q --depth 1 "https://github.com/nginx-proxy/${TOOL}" "${COMMIT}" && git checkout -q FETCH_HEAD
            [ "$(git rev-parse HEAD)" = "${COMMIT}" ] || { echo "fetched $(git rev-parse HEAD), not ${COMMIT}"; exit 1; }
            go version
            # shellcheck disable=SC2086 # one argument per module@version
            go get ${BUMPS}
            go mod tidy
            mkdir /out
            { echo "// generated by scripts/update-go-deps.sh for ${COMMIT}: do not edit"; cat go.mod; } > /out/go.mod
            cp go.sum /out/go.sum
            tar -C /out -cf - go.mod go.sum >&3' | tar -C "$tmp" -xf -
    mkdir -p "$ROOT/go/$tool"
    mv "$tmp/go.mod" "$tmp/go.sum" "$ROOT/go/$tool/"
    rmdir "$tmp"
    echo "    go/${tool}/go.mod, go.sum written"
}

case "${1:-all}" in
    all) gen docker-gen "$DOCKER_GEN_COMMIT" "$DOCKER_GEN_GO_GET"; gen forego "$FOREGO_COMMIT" "$FOREGO_GO_GET" ;;
    docker-gen) gen docker-gen "$DOCKER_GEN_COMMIT" "$DOCKER_GEN_GO_GET" ;;
    forego) gen forego "$FOREGO_COMMIT" "$FOREGO_GO_GET" ;;
    *) echo "usage: scripts/update-go-deps.sh [docker-gen|forego]" >&2; exit 2 ;;
esac
